const SUPPORTED_LANGS: Language[] = ['en', 'de', 'ar', 'ru'];

export const LanguageProvider: React.FC<{ children: React.ReactNode }> = ({ children }) => {
  const [language, setLanguageState] = useState<Language>(() => {
    if (typeof window !== 'undefined') {
      const firstSegment = window.location.pathname.replace(/^\/+|\/+$/g, '').split('/')[0] as Language;
      if (SUPPORTED_LANGS.includes(firstSegment)) {
        return firstSegment;
      }
      const saved = localStorage.getItem('pegasus_lang') as Language;
      if (saved && SUPPORTED_LANGS.includes(saved)) {
        return saved;
      }
    }
    return 'en';
  });

  const direction: Direction = language === 'ar' ? 'rtl' : 'ltr';

  const setLanguage = (lang: Language) => {
    setLanguageState(lang);
    localStorage.setItem('pegasus_lang', lang);
  };

  useEffect(() => {
    document.documentElement.lang = language;
    document.documentElement.dir = direction;
  }, [language, direction]);

  const t = (key: string, defaultText?: string): string => {
    const dict = translations[language as Language];
    if (dict && dict[key]) {
      return dict[key];
    }
    // Fallback to English
    if (translations.en[key]) {
      return translations.en[key];
    }
    return defaultText || key;
  };

  return (
    <LanguageContext.Provider value={{ language, direction, setLanguage, t }}>
      {children}
    </LanguageContext.Provider>
  );
};

export const useLanguage = () => useContext(LanguageContext);
